// Builds the deployable static asset tree for Cloudflare Workers.
//
// The Apache and Node deployments both serve a strict allowlist of public
// files (see .htaccess and server.js). Cloudflare uploads whatever sits in the
// assets directory, so the allowlist is reproduced here: only these files are
// copied into dist/, which keeps private folders (Antrag/, data/, tests/) out
// of the deployment by construction.

import { cp, mkdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DIST = path.join(ROOT, "dist");

const PUBLIC_FILES = [
  "index.html",
  "app.js",
  "styles.css",
  "robots.txt",
  "site.webmanifest",
  "favicon.ico",
  "favicon.png",
  "apple-touch-icon.png",
  "content/articles.json",
  "content/articles-2026-expansion.json",
  "assets/action-funding-logo-rgb.jpg",
  "assets/action-funding-logo-rgb.webp",
  "assets/cyri-logo.svg",
  "assets/cyri-logo-192.png",
  "assets/cyri-logo-512.png",
  "assets/antigravity.js",
  "assets/learning-3d.js",
  "assets/specular-buttons.js",
  "assets/photos/aletsch-glacier-hd.jpg",
  "assets/photos/coral-bleaching-florida-2023-hd.jpg",
  "assets/photos/coral-reef-bleaching-hd.jpg",
  "assets/photos/coral-reef-bleaching-hd.webp",
  "assets/photos/mangrove-forest-hd.jpg",
  "assets/photos/ocean-plastic-hd.jpg",
  "assets/photos/offshore-wind-hd.jpg",
  "assets/photos/seagrass-meadow-zostera-hd.jpg",
  "assets/photos/sponge-city-rain-garden-hd.jpg",
  "assets/vendor/three/three.core.min.js",
  "assets/vendor/three/three.module.min.js",
  ...Array.from(
    { length: 17 },
    (_, index) => `assets/sdg/E_SDG_Icons-${String(index + 1).padStart(2, "0")}.jpg`
  ),
];

// sitemap.xml is generated by the Worker from the live article list, so the
// checked-in copy is deliberately not deployed.
const HEADERS_FILE = `# Generated by scripts/build-cloudflare.mjs - do not edit dist/ by hand.
/*
  Content-Security-Policy: default-src 'self'; base-uri 'self'; connect-src 'self'; font-src 'self' data:; frame-ancestors 'none'; form-action 'self'; img-src 'self' data: blob:; object-src 'none'; script-src 'self'; style-src 'self' 'unsafe-inline'
  Permissions-Policy: camera=(), geolocation=(), microphone=(), payment=(), usb=()
  Referrer-Policy: strict-origin-when-cross-origin
  Cross-Origin-Opener-Policy: same-origin
  Cross-Origin-Resource-Policy: same-site
  X-Permitted-Cross-Domain-Policies: none
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY

/assets/*
  Cache-Control: public, max-age=3600

/content/*
  Cache-Control: public, max-age=3600
`;

async function build() {
  await rm(DIST, { recursive: true, force: true });
  await mkdir(DIST, { recursive: true });

  const missing = [];
  for (const relativePath of PUBLIC_FILES) {
    const source = path.join(ROOT, relativePath);
    const target = path.join(DIST, relativePath);
    await mkdir(path.dirname(target), { recursive: true });
    try {
      await cp(source, target);
    } catch {
      missing.push(relativePath);
    }
  }

  if (missing.length) {
    throw new Error(`Missing public files:\n  ${missing.join("\n  ")}`);
  }

  await writeFile(path.join(DIST, "_headers"), HEADERS_FILE, "utf8");
  console.log(`Built dist/ with ${PUBLIC_FILES.length} files.`);
}

build().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
